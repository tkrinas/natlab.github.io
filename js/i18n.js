var swapTimer = 0;

function resolveLang() {
    var q = null;
    try {
        q = new URLSearchParams(location.search).get("lang");
    } catch (e) {}
    if (q === "en" || q === "el") return q;
    try {
        var stored = localStorage.getItem("lang");
        if (stored === "en" || stored === "el") return stored;
    } catch (e2) {}
    return "en";
}

function contentAnchor() {
    var nodes = document.querySelectorAll("h1, h2, h3, p, li");
    var viewH = window.innerHeight;
    for (var i = 0; i < nodes.length; i++) {
        if (nodes[i].closest("#sideNav")) continue;
        var top = nodes[i].getBoundingClientRect().top;
        if (top >= 64 && top < viewH) return { el: nodes[i], top: top };
    }
    return null;
}

function holdAnchor(mark) {
    if (!mark || !mark.el) return;
    var delta = mark.el.getBoundingClientRect().top - mark.top;
    if (Math.abs(delta) <= 1) return;
    var root = document.documentElement;
    var prev = root.style.scrollBehavior;
    root.style.scrollBehavior = "auto";
    window.scrollBy(0, delta);
    root.style.scrollBehavior = prev;
}

function applyLang(lang, animate) {
    if (lang !== "en" && lang !== "el") lang = "en";
    var ready = document.documentElement.classList.contains("i18n-ready");
    if (ready && document.documentElement.lang === lang) return;
    var reduce = false;
    try {
        reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    } catch (e) {}
    if (swapTimer) {
        clearTimeout(swapTimer);
        swapTimer = 0;
    }
    var mark = animate ? contentAnchor() : null;
    if (animate && !reduce) {
        document.documentElement.classList.add("i18n-swap");
        requestAnimationFrame(function () { holdAnchor(mark); });
        swapTimer = setTimeout(function () {
            swapTimer = 0;
            document.body.style.overflowAnchor = "none";
            writeLang(lang);
            holdAnchor(mark);
            holdAnchor(mark);
            document.body.style.overflowAnchor = "";
            document.documentElement.classList.remove("i18n-swap");
        }, 150);
        return;
    }
    document.documentElement.classList.remove("i18n-swap");
    writeLang(lang);
    holdAnchor(mark);
}

function writeLang(lang) {
    var dict = STRINGS[lang];
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
        var key = el.getAttribute("data-i18n");
        var value = dict[key];
        if (value == null) {
            console.warn("missing i18n key: " + key);
            return;
        }
        el.textContent = value;
    });
    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
        el.getAttribute("data-i18n-attr").split(";").forEach(function (pair) {
            var i = pair.indexOf(":");
            if (i < 1) return;
            var attr = pair.slice(0, i).trim();
            var key = pair.slice(i + 1).trim();
            var value = dict[key];
            if (value == null) {
                console.warn("missing i18n key: " + key);
                return;
            }
            el.setAttribute(attr, value);
        });
    });
    document.querySelectorAll(".lang-switch [data-lang]").forEach(function (btn) {
        btn.setAttribute("aria-pressed", btn.getAttribute("data-lang") === lang ? "true" : "false");
    });
    try {
        localStorage.setItem("lang", lang);
    } catch (e) {}
    try {
        var url = new URL(location.href);
        if (lang === "en") url.searchParams.delete("lang");
        else url.searchParams.set("lang", lang);
        if (url.href !== location.href) history.replaceState(null, "", url);
    } catch (e2) {}
    document.documentElement.classList.add("i18n-ready");
}
